const { chromium } = require('playwright'); const fs = require('fs');
const BASE = 'http://localhost:4340', PAGE = '/anna/home.html';
const api = async (body, key) => { const r = await fetch(BASE + '/_lab/api/comments', { method: 'POST', headers: { 'content-type': 'application/json', ...(key ? { 'x-lab-admin': key } : {}) }, body: JSON.stringify({ page: PAGE, ...body }) }); return { status: r.status, data: await r.json().catch(() => ({})) }; };
const list = async () => (await (await fetch(BASE + '/_lab/api/comments?page=' + PAGE)).json()).comments;
const res = []; const check = (n, ok, note = '') => { res.push({ name: n, ok: !!ok }); console.log(ok ? 'ok  ' : 'FAIL', n, note); };
(async () => {
  const key = (await api({ action: 'invite', name: 'anna' }, 'admintoken')).data.key;
  const t = (await api({ name: 'sam', text: 'thread to delete', anchor: { selector: 'h1', x: .2, y: .5, docX: .2, docY: 60 } })).data.comment;
  await api({ name: 'tom', text: 'reply one', parent: t.id }); await api({ name: 'sam', text: 'reply two', parent: t.id });
  const keep = (await api({ name: 'tom', text: 'this one stays', anchor: { selector: 'h1', x: .8, y: .5, docX: .5, docY: 60 } })).data.comment;
  check('before: 1 thread with 2 replies + 1 other', (await list()).length === 4);
  check('a reviewer cannot delete', (await api({ action: 'delete', id: t.id })).status === 403);
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1200, height: 760 } });
  await ctx.addInitScript(() => { try { localStorage.setItem('lab-on', '1'); localStorage.setItem('lab-hint-seen', '1'); localStorage.setItem('lab-name', 'anna'); } catch {} });
  const p = await ctx.newPage(); let asked = '';
  p.on('dialog', d => { asked = d.message(); d.dismiss(); });
  await p.goto(BASE + PAGE + '?lab-admin=' + key); await p.waitForTimeout(700);
  const L = (s) => p.locator(`[data-lab-comments] ${s}`);
  await L('button.pin').filter({ hasText: 'S' }).click(); await p.waitForTimeout(300);
  await L('.card .btn').filter({ hasText: 'delete' }).click(); await p.waitForTimeout(400);
  check('delete asks first', asked.includes('delete'), asked);
  check('cancel keeps everything', (await list()).length === 4);
  p.removeAllListeners('dialog'); p.on('dialog', d => d.accept());
  await L('.card .btn').filter({ hasText: 'delete' }).click(); await p.waitForTimeout(800);
  const after = await list();
  check('delete removes the thread and both replies', after.length === 1 && after[0].id === keep.id, after.map(c => c.text).join(' | '));
  check('the pin is gone from the page', await L('button.pin').count() === 1);
  const agent = await (await fetch(BASE + '/_lab/agent' + PAGE)).text();
  check('agent link no longer mentions it', !agent.includes('thread to delete') && !agent.includes('reply one') && agent.includes('this one stays'));
  check('remaining comment is renumbered 1', /## 1\. tom/.test(agent));
  await p.reload(); await p.waitForTimeout(700);
  check('still gone after reload', await L('button.pin').count() === 1);
  check('deleting again says not found', (await api({ action: 'delete', id: t.id }, key)).status === 404);
  check('deleting a single reply keeps the thread', await (async () => { const r = (await api({ name: 'x', text: 'r', parent: keep.id })).data.comment; await api({ action: 'delete', id: r.id }, key); const l = await list(); return l.length === 1 && l[0].id === keep.id; })());
  fs.writeFileSync(__dirname + '/results-delete.json', JSON.stringify({ results: res, shots: [] }));
  console.log(res.filter(r => r.ok).length + '/' + res.length); await b.close();
})();
